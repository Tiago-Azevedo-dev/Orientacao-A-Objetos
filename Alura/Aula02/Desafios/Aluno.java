public class Aluno {
    private String nome;
    private double notas;
    public void setNome(String nome) {
        this.nome = nome;
    }
    public void setNotas(double nota) {
        this.notas = nota;
    }
    public String getNome() {
        return nome;
    }
    public double getNotas() {
        return notas;
    }
}
